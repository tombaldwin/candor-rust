#!/usr/bin/env bash
# install.sh — install the candor Claude Code integration into a Rust project.
#
#   ./install.sh [TARGET_PROJECT_DIR]   (defaults to cwd)
#
# Distribution model: the candor CLONE is the single source of truth. The project gets
# only thin STUBS that delegate to the clone's real scripts, so `git pull` (or
# `cargo candor update`) in the clone updates the engine, these scripts, AND AGENTS.md
# together — nothing in the project goes stale independently.
#
# Installs into <target>:
#   .claude/candor/candor-run.sh, stop-hook.sh   stubs -> $CANDOR_HOME/integrations/...
#   .claude/commands/candor.md                   the /candor slash command
#   .claude/settings.json                        merges in the Stop hook (auto-refresh)
#   .candor/config                               pins CANDOR_HOME (clone) + CANDOR_LIB
#
# Idempotent: re-running re-points stubs and re-merges the hook. Run it again after you
# move the clone or to migrate an older copy-based install to the reference model.
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CANDOR_HOME="$(cd "$SRC/../.." && pwd)"   # the clone root (…/candor)
TARGET="${1:-$PWD}"
TARGET="$(cd "$TARGET" && pwd)"
[ -f "$TARGET/Cargo.toml" ] || { echo "error: $TARGET is not a Rust project (no Cargo.toml)"; exit 1; }

echo "Installing candor Claude Code integration into: $TARGET"
echo "  candor clone (source of truth): $CANDOR_HOME"
mkdir -p "$TARGET/.claude/candor" "$TARGET/.claude/commands" "$TARGET/.candor"

# --- thin stubs: project-relative registration, logic delegated to the clone ---
for s in candor-run stop-hook; do
  cat > "$TARGET/.claude/candor/$s.sh" <<EOF
#!/usr/bin/env bash
# STUB — generated by candor install.sh. Delegates to the candor clone so that
# \`git pull\` / \`cargo candor update\` in the clone updates the real logic. Do not edit.
DIR="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")/../.." && pwd)"   # project root
[ -f "\$DIR/.candor/config" ] && . "\$DIR/.candor/config"
REAL="\${CANDOR_HOME:-}/integrations/claude-code/$s.sh"
if [ -n "\${CANDOR_HOME:-}" ] && [ -x "\$REAL" ]; then
  exec "\$REAL" "\$@"
fi
# Clone missing/moved: a hook must never break the session, so stay quiet.
[ "$s" = "candor-run" ] && echo "candor ⚠ clone not found — re-run candor's install.sh or fix CANDOR_HOME in .candor/config."
exit 0
EOF
  chmod +x "$TARGET/.claude/candor/$s.sh"
done
cp "$SRC/commands/candor.md" "$TARGET/.claude/commands/"

# --- pin the clone (and the resolved dylib + query binary) in the project config ---
LIB="$(ls "$CANDOR_HOME"/target/debug/libcandor@*.dylib "$CANDOR_HOME"/target/debug/libcandor@*.so 2>/dev/null | head -1 || true)"
# candor-query powers the receipt's effect breakdown + self-review. A bare `cargo build` builds the
# dylib but NOT candor-query (it's not a dependency of the lint), so build it here if it's missing —
# it's a small stable crate, quick to compile.
QUERY=""
for q in "$CANDOR_HOME"/target/release/candor-query "$CANDOR_HOME"/target/debug/candor-query \
         "${CANDOR_CACHE:-$HOME/.candor}"/bin/candor-query; do
  [ -x "$q" ] && { QUERY="$q"; break; }
done
if [ -z "$QUERY" ]; then
  echo "  building candor-query (receipt breakdown + self-review)…"
  ( cd "$CANDOR_HOME" && cargo build -q -p candor-query ) 2>/dev/null || true
  [ -x "$CANDOR_HOME/target/debug/candor-query" ] && QUERY="$CANDOR_HOME/target/debug/candor-query"
fi
{
  printf 'CANDOR_HOME=%q\n' "$CANDOR_HOME"
  [ -n "$LIB" ] && printf 'CANDOR_LIB=%q\n' "$LIB"
  [ -n "$QUERY" ] && printf 'CANDOR_QUERY=%q\n' "$QUERY"
} > "$TARGET/.candor/config"
if [ -n "$LIB" ]; then echo "  pinned CANDOR_HOME and CANDOR_LIB"; else
  echo "  pinned CANDOR_HOME. No dylib built yet — run 'cargo candor update' (or 'cargo build' in the clone)."
fi
[ -n "$QUERY" ] && echo "  pinned CANDOR_QUERY ($(basename "$(dirname "$(dirname "$QUERY")")")/$(basename "$(dirname "$QUERY")")/candor-query)" \
  || echo "  ⚠ candor-query unavailable — the receipt will show a crude count until you run 'cargo candor setup'."

# --- merge the Stop hook into .claude/settings.json (non-destructive) ---
SETTINGS="$TARGET/.claude/settings.json"
HOOK_CMD='${CLAUDE_PROJECT_DIR}/.claude/candor/stop-hook.sh'
if command -v python3 >/dev/null 2>&1; then
  python3 - "$SETTINGS" "$HOOK_CMD" <<'PY'
import json, os, sys
path, cmd = sys.argv[1], sys.argv[2]
data = {}
if os.path.exists(path):
    try:
        data = json.load(open(path))
    except Exception:
        # The file exists but isn't plain JSON — most likely comments / trailing commas, which Claude
        # Code itself accepts but json.load rejects. Do NOT reset-and-overwrite (that would WIPE the
        # user's permissions/env/model/other hooks). Leave it untouched and print the manual snippet.
        sys.stderr.write("  WARNING: %s isn't plain JSON (comments or trailing commas?) — NOT modifying it.\n" % path)
        sys.stderr.write('  Add this Stop hook by hand: {"matcher":"*","hooks":[{"type":"command","command":"%s"}]}\n' % cmd)
        sys.exit(0)
stop = data.setdefault("hooks", {}).setdefault("Stop", [])
def has(c):
    return any(h.get("command") == c for g in stop for h in g.get("hooks", []))
if not has(cmd):
    stop.append({"matcher": "*", "hooks": [{"type": "command", "command": cmd}]})
json.dump(data, open(path, "w"), indent=2); open(path, "a").write("\n")
print("  merged Stop hook into", path)
PY
else
  echo "  python3 not found — add this to $SETTINGS manually:"
  echo '    {"hooks":{"Stop":[{"matcher":"*","hooks":[{"type":"command","command":"'"$HOOK_CMD"'"}]}]}}'
fi

# --- keep generated artifacts out of git (baseline stays opt-in to commit) ---
GI="$TARGET/.gitignore"
grep -qxF '.candor/report.*.json' "$GI" 2>/dev/null || {
  # Ensure the file ends with a newline first, else the first pattern fuses onto the last existing
  # line (which both breaks that ignore pattern AND makes the grep above never match → re-append forever).
  if [ -s "$GI" ] && [ -n "$(tail -c1 "$GI" 2>/dev/null)" ]; then echo >> "$GI"; fi
  { echo '.candor/report.*.json'; echo '.candor/state'; echo '.candor/last-error.log'; } >> "$GI"
}

echo "Done. Updates flow from the clone: 'cargo candor update' (or git pull + ./install.sh) there"
echo "refreshes the engine, these scripts, and AGENTS.md at once. Try '/candor' in Claude Code."
