#!/usr/bin/env bash
# gen/std_assoc.sh [--check | --selftest] — regenerate src/std_assoc.tsv from the rust-src of the PINNED toolchain, verify (--check) that the
# committed table reproduces from it byte for byte, or (--selftest) prove the generator's self-check can FAIL: each scope row kind (`P`, `G`,
# `N`, `TC`; SOUNDNESS R1951/R1956) is dropped in turn with `STD_ASSOC_SELFCHECK_DROP_ROW` and the generator must refuse (exit 3), while the
# undropped run must pass (exit 0). The pin is the `rustc -V` in the table's first line, as for `std_bounds.sh`.
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"; CRATE="$(cd "$HERE/.." && pwd)"
TABLE="$CRATE/src/std_assoc.tsv"
TC="${STD_BOUNDS_TOOLCHAIN:-stable}"
RUSTC_V="$(rustup run "$TC" rustc -V)" || { echo "std_assoc.sh: no toolchain '$TC'" >&2; exit 2; }
SRC="$(rustup run "$TC" rustc --print sysroot)/lib/rustlib/src/rust/library"
[ -d "$SRC/core/src" ] || { echo "std_assoc.sh: no rust-src for $TC ($SRC)" >&2; exit 2; }
PIN="$(head -1 "$TABLE" | sed -n 's/.*rust-src of \(rustc [^—]*\) — .*/\1/p' | sed 's/ *$//')"
gen() {
  printf '# GENERATED by crates/candor-scan/gen/std_assoc.py from the rust-src of %s — do not edit by hand.\n' "$RUSTC_V"
  sed -n 2p "$TABLE"
  python3 "$HERE/std_assoc.py" "$SRC"
}
case "${1:-}" in
  --check|--selftest)
    if [ "$PIN" != "$RUSTC_V" ]; then
      echo "std_assoc.sh: the table is pinned to '$PIN'; toolchain '$TC' is '$RUSTC_V' — set STD_BOUNDS_TOOLCHAIN to the pinned one" >&2
      exit 2
    fi ;;
esac
case "${1:-}" in
  --check)
    out="$(gen)" || { echo "std_assoc.sh: the generator refused" >&2; exit 1; }
    if [ "$out" != "$(cat "$TABLE")" ]; then echo "std_assoc.sh: $TABLE does not reproduce from $SRC ($RUSTC_V)" >&2; exit 1; fi
    echo "std_assoc.sh: $TABLE reproduces" ;;
  --selftest)
    python3 "$HERE/std_assoc.py" "$SRC" >/dev/null || { echo "std_assoc.sh: the undropped run refused" >&2; exit 1; }
    bad=0
    for d in 'P|2015|Default' 'P|2021|Extend' 'P|2021|TryFrom' 'P|2024|Future' \
             'G|std::os::unix::prelude|std::os::unix::ffi::os_str::OsStrExt' 'G|std::os::windows::prelude|std::os::windows::ffi::OsStrExt' \
             'G|std::os::unix::ffi|std::os::unix::ffi::os_str::OsStringExt' 'G|std::os::unix::process|std::os::unix::process::CommandExt' \
             'N|std::os::unix::prelude::CommandExt|std::os::unix::process::CommandExt' 'N|std::os::windows::fs::FileTypeExt|std::os::windows::fs::FileTypeExt' \
             'TC|from_vec|std::os::unix::ffi::os_str::OsStringExt' 'TC|from_bytes|std::os::unix::ffi::os_str::OsStrExt' 'TC|uid|std::os::unix::process::CommandExt'; do
      STD_ASSOC_SELFCHECK_DROP_ROW="$d" python3 "$HERE/std_assoc.py" "$SRC" >/dev/null 2>&1
      rc=$?
      if [ "$rc" = 3 ]; then echo "  refused, as it must: drop $d"; else echo "  NOT REFUSED (rc=$rc): drop $d"; bad=1; fi
    done
    if [ "$bad" != 0 ]; then echo "std_assoc.sh: selftest FAILED" >&2; exit 1; fi
    echo "std_assoc.sh: selftest OK" ;;
  "")
    gen > "$TABLE.tmp" && mv "$TABLE.tmp" "$TABLE" ;;
  *) echo "usage: gen/std_assoc.sh [--check | --selftest]" >&2; exit 2 ;;
esac
